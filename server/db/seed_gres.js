const db = require('./index.js');
const J = o => JSON.stringify(o);
const SUP = db.prepare('SELECT * FROM supplier').all();
const sup = n => SUP.find(s => s.name.includes(n)) || SUP[0] || { id: '', name: '' };

let nid = {};
const mk = (type, pfx) => { nid[type] = (nid[type] || 0) + 1; return pfx + String(nid[type]).padStart(4, '0'); };

/* 资源本身不带价也不归属供应商；示范价按 r.sp 那家供应商写进 gres_rate，
   等于「这家供应商给这个单元报过价」。 */
function add(type, pfx, r, units) {
  const id = mk(type, pfx);
  db.prepare(`INSERT INTO gres (id,type,name,name_en,country,city,addr,level,supplier_id,supplier_name,
    contact,phone,tags,cover,images,intro,ext,currency,rating,used,status,memo)
    VALUES (@id,@type,@name,@name_en,@country,@city,@addr,@level,@supplier_id,@supplier_name,
    @contact,@phone,@tags,@cover,@images,@intro,@ext,'CNY',@rating,@used,'on',@memo)`).run({
    id, type, name: r.n, name_en: r.en || '', country: r.co, city: r.ci, addr: r.ad || '',
    level: r.lv || '', supplier_id: '', supplier_name: '',
    contact: r.ct || '', phone: r.ph || '', tags: J(r.tg || []), cover: '', images: J([]),
    intro: r.in || '', ext: J(r.ext || {}), rating: r.rt || 4.5, used: r.us || 0, memo: r.mm || '',
  });
  const s = r.sp ? sup(r.sp) : { id: 'PLATFORM', name: '平台直采' };
  units.forEach((u, i) => {
    const uid = db.prepare(`INSERT INTO gres_unit (res_id,name,spec,unit,cost,price,cap,min_pax,season,stock,status,sort)
      VALUES (?,?,?,?,0,0,?,?,?,?, 'on', ?)`).run(id, u[0], u[1], u[2], u[5] || 0, u[6] || 0, u[7] || '全年', u[8] || '', i).lastInsertRowid;
    if (u[3]) db.prepare(`INSERT INTO gres_rate (res_id,unit_id,supplier_id,supplier_name,cost,tax,status,memo)
      VALUES (?,?,?,?,?, '含税', 'on', '示范报价')`).run(id, uid, s.id, s.name, u[3]);
  });
  const lo = db.prepare(`SELECT MIN(cost) c FROM gres_rate WHERE res_id=? AND status='on' AND cost>0`).get(id).c;
  db.prepare('UPDATE gres SET cost_from=?, price_from=0 WHERE id=?').run(lo || 0, id);
}

